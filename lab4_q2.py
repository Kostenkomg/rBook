    print("\n=== Часть 2 ===")

    print(f"[i**2 for i in range(10) if i < 3] = "
          f"{[i**2 for i in range(10) if i < 3]}")

    lst = ['привет' for i in [1, 2, 3]]
    print(f"lst                                = {lst}")
    print(f"lst + [i for i in ['1','2','3']]  = "
          f"{lst + [i for i in ['1', '2', '3']]}")


