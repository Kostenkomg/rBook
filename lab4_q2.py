"""
Лабораторная работа № 4: Абстракция данных и списки
====================================================

Вопрос 2. Списковые включения (list comprehensions).

Списковое включение — это компактный способ создания нового списка
на основе другого итерируемого объекта.

Общий синтаксис:
    [выражение for элемент in итерируемый_объект if условие]

- "выражение"  — что положить в новый список;
- "элемент"    — переменная-счётчик;
- "итерируемый_объект" — источник данных (range, список, строка и т.д.);
- "if условие" — необязательный фильтр, отбрасывающий ненужные элементы.

Списковые включения работают быстрее и короче, чем эквивалентный цикл for.
"""


